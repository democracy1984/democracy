"""Тексты агитации в ЛС после наказания.

Слегка рандомизируем сообщение: случайная комбинация начала, середины
и концовки. Смысл и стиль сохраняются, текущий вариант — один из возможных.
"""

import random

OPENINGS = (
    "Тебя совершенно несправедливо {action_word} в чате {chat_title}, это ВОЗМУТИТЕЛЬНО!!!",
    "Тебя абсолютно несправедливо {action_word} в чате {chat_title}. Это ВОЗМУТИТЕЛЬНО!!!",
    "В чате {chat_title} тебя несправедливо {action_word} — это просто ВОЗМУТИТЕЛЬНО!!!",
    "Тебя {action_word} в чате {chat_title}? Это вопиющий акт диктаторского произвола!",
)

MIDDLES = (
    "ДОВОЛЬНО ЭТО ТЕРПЕТЬ!!! Вставай на путь демократии и свободы выбора!!!",
    "ХВАТИТ ЭТО ТЕРПЕТЬ!!! Пора вставать на путь демократии и свободы выбора!!!",
    "СКОЛЬКО МОЖНО ЭТО ТЕРПЕТЬ?! Вставай на путь демократии и свободы выбора!!!",
    "ЭТО НЕЛЬЗЯ ТЕРПЕТЬ!!! Вставай на путь демократии и свободы выбора!!!",
    "ХВАТИТ МОЛЧАТЬ!!! Вставай на путь демократии и свободы выбора!!!",
    "ДОВОЛЬНО МОЛЧАТЬ!!! Вставай на путь демократии и свободы выбора!!!",

)

ENDINGS = (
    "Присоединяйся к нашему походу за справедливость, распространяй стикер, ВЫБОРЫ ЕСТЬ!!!",
    "Присоединяйся к борьбе за справедливость, распространяй стикер — ВЫБОРЫ ЕСТЬ!!!",
    "Мы нуждаемся в тебе для борьбы за справедливость. Распространяй стикер — ВЫБОРЫ ЕСТЬ!!!",
    "Вступай в наши ряды справедливости и демократии, распространяй стикер, ВЫБОРЫ ЕСТЬ!!!",
    "Ты нам нужен для борьбы за справедливость, распространяй стикер. ВЫБОРЫ ЕСТЬ!!!",
)


def build_promo_text(action_word, chat_title, chooser=random.choice):
    """Собирает случайное сообщение из начала, середины и концовки."""
    opening = chooser(OPENINGS).format(action_word=action_word, chat_title=chat_title)
    middle = chooser(MIDDLES)
    ending = chooser(ENDINGS)
    return f"{opening}\n{middle}\n{ending}"


VICTORY_PHRASES = (
    "🕊 Очередная победа демократии!",
    "🕊 Ещё одна победа демократии!",
    "🕊 Демократия восторжествовала!",
    "🕊 Свобода слова снова победила!",
    "🕊 Демократия непобедима!",
    "🕊 Ещё один шаг к свободе слова!",
    "🕊 Режим отступил — демократия торжествует!",
    "🕊 Маленькая победа в большой войне!",
)


def build_victory_text(chooser=random.choice):
    """Случайная фраза-реакция на размут."""
    return chooser(VICTORY_PHRASES)
